"""Actual copied-source/data process replay; not checkpoint or publication admission."""
import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
from render import identity, read, need

HERE = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    out = args.output
    need(out.is_absolute() and not out.exists()
         and not any(p.is_symlink() for p in (out, *out.parents)), 'Use a new ordinary absolute directory')
    out.mkdir(parents=True, exist_ok=False)
    shutil.copytree(HERE / 'bundle', out / 'bundle')
    shutil.copyfile(HERE / 'render.py', out / 'render.py')
    need(identity(out / 'render.py') == identity(HERE / 'render.py'), 'Copied renderer differs')
    env = {k: v for k, v in os.environ.items() if k != 'PYTHONPATH'}
    env.update(CUDA_VISIBLE_DEVICES='', OMP_NUM_THREADS='1', OPENBLAS_NUM_THREADS='1', MKL_NUM_THREADS='1')
    command = [sys.executable, '-B', str(out / 'render.py'), '--bundle', str(out / 'bundle'),
               '--output', str(out / 'results')]
    result = subprocess.run(command, cwd=out, env=env, capture_output=True, text=True)
    run = dict(command=command, returncode=result.returncode, stdout=result.stdout, stderr=result.stderr)
    with (out / 'execution.json').open('x') as stream:
        json.dump(run, stream, sort_keys=True, indent=2)
        stream.write('\n')
    need(result.returncode == 0, 'Actual cold renderer failed; original execution preserved')
    original = read(HERE / 'actual/verification.json')
    compared = {}
    for name in (*original['outputs'], 'verification.json'):
        a, b = HERE / 'actual' / name, out / 'results' / name
        need(identity(a) == identity(b) and a.read_bytes() == b.read_bytes(), 'Cold generated bytes differ: ' + name)
        compared[name] = identity(a)
    receipt = dict(scope='actual-copied-source-data-fragment-replay',
        source=identity(HERE / 'render.py'), outputs_compared=compared,
        original_input_manifest=identity(HERE / 'bundle/inputs.json'),
        actual_child_returncode=result.returncode, actual_outputs_all_byte_exact=True,
        original_producer_paths_not_used=True, physical_second_host=False,
        model_admission=False, source_publication=False, scientific_completion=False)
    with (out / 'verification.json').open('x') as stream:
        json.dump(receipt, stream, indent=2, sort_keys=True, allow_nan=False)
        stream.write('\n')
    print(json.dumps(dict(output=str(out), verification=identity(out / 'verification.json'),
                          actual_child_returncode=result.returncode, outputs_compared=len(compared))))


if __name__ == '__main__':
    main()
