def archived_sources() -> dict[str, bytes]:
    """Decode archive members without trusting offsets stored outside the records."""

    try:
        raw = zlib.decompress(base64.b85decode(_PACKED_B85))
    except (ValueError, zlib.error) as error:
        raise ValueError("invalid compressed evaluator source archive") from error
    expected_bytes = sum(int(record["bytes"]) for record in SOURCE_RECORDS.values())
    if len(raw) != expected_bytes:
        raise ValueError(
            f"evaluator source archive has {len(raw)} bytes, expected {expected_bytes}"
        )
    sources: dict[str, bytes] = {}
    offset = 0
    for label, record in SOURCE_RECORDS.items():
        end = offset + int(record["bytes"])
        sources[label] = raw[offset:end]
        offset = end
    if offset != len(raw):
        raise ValueError("evaluator source archive has trailing bytes")
    return sources
